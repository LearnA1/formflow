import pypdf
import io
from pathlib import Path
from services.form_catalog_service import get_form_by_id

# Where filled PDFs are saved temporarily
OUTPUT_DIR = Path(__file__).parent.parent / "filled_forms"
OUTPUT_DIR.mkdir(exist_ok=True)

# Where template PDFs live
FORMS_DIR = Path(__file__).parent.parent / "forms"


def fill_pdf(session_id: str, form_id: str, answers: dict) -> dict:
    """
    Fill a PDF template with answers and save the result.
    Returns a dict with the output path, or an error.
    """
    form = get_form_by_id(form_id)
    if not form:
        return {"error": f"Form '{form_id}' not found in catalog."}

    template_path = FORMS_DIR / Path(form["local_path"]).name

    # If the actual PDF doesn't exist yet (MVP demo mode), create a simple text report instead
    if not template_path.exists():
        return _create_text_report(session_id, form, answers)

    try:
        reader = pypdf.PdfReader(str(template_path))
        writer = pypdf.PdfWriter()
        writer.append(reader)

        # Fill all pages
        for page in writer.pages:
            writer.update_page_form_field_values(page, answers)

        output_path = OUTPUT_DIR / f"{session_id}_filled.pdf"
        with open(output_path, "wb") as f:
            writer.write(f)

        return {
            "status": "filled",
            "session_id": session_id,
            "output_path": str(output_path),
            "filename": f"{session_id}_filled.pdf",
        }

    except Exception as e:
        return {"error": str(e)}


def _create_text_report(session_id: str, form: dict, answers: dict) -> dict:
    """
    Fallback: when no real PDF template exists, generate a readable text summary.
    This lets the MVP work end-to-end even before real PDFs are added.
    """
    from reportlab.lib.pagesizes import letter
    from reportlab.pdfgen import canvas as rl_canvas

    output_path = OUTPUT_DIR / f"{session_id}_filled.pdf"

    c = rl_canvas.Canvas(str(output_path), pagesize=letter)
    width, height = letter

    # Header
    c.setFont("Helvetica-Bold", 18)
    c.drawString(50, height - 60, form["title"])

    c.setFont("Helvetica", 11)
    c.setFillColorRGB(0.4, 0.4, 0.4)
    c.drawString(50, height - 80, f"Completed by FormFlow AI  |  Session: {session_id}")

    # Divider
    c.setStrokeColorRGB(0.8, 0.8, 0.8)
    c.line(50, height - 95, width - 50, height - 95)

    # Fields
    y = height - 130
    c.setFont("Helvetica-Bold", 10)
    c.setFillColorRGB(0.5, 0.5, 0.5)
    c.drawString(50, y, "FIELD")
    c.drawString(280, y, "YOUR ANSWER")
    y -= 20

    for field in form.get("fields", []):
        name = field["field_name"]
        value = answers.get(name, "—")

        # Mask SSN for security
        if "ssn" in name.lower() and len(value) > 4:
            value = "***-**-" + value[-4:]

        c.setFont("Helvetica", 10)
        c.setFillColorRGB(0.3, 0.3, 0.3)
        c.drawString(50, y, name.replace("_", " ").title())

        c.setFont("Helvetica-Bold", 10)
        c.setFillColorRGB(0, 0, 0)
        c.drawString(280, y, str(value))

        y -= 22
        if y < 80:
            c.showPage()
            y = height - 60

    # Footer
    c.setFont("Helvetica", 9)
    c.setFillColorRGB(0.6, 0.6, 0.6)
    c.drawString(50, 40, "Generated by FormFlow — AI Paperwork Assistant")

    c.save()

    return {
        "status": "filled",
        "session_id": session_id,
        "output_path": str(output_path),
        "filename": f"{session_id}_filled.pdf",
        "note": "Demo mode: real PDF template not found, generated summary instead.",
    }